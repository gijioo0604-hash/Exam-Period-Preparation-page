/* ============================================================
   검사.mjs — 시험대비.html 이 기준을 지켰는지 기계로 세어 보는 스크립트
   ============================================================

   쓰는 법 (이 파일이 있는 폴더에서):

       node 검사.mjs

   무엇을 검사하는가
     기준1  문제가 10개 이상인가
     기준2  모든 문제에 정답과 해설이 있는가
     기준3  모든 해설에 출처 파일명(.md)이 적혀 있는가
     기준4  디자인.md 표의 색과 글자 크기만 썼는가

   기준의 출처 — 이 스크립트에 적어 두지 않았습니다
     - 검사할 기준 목록은 완료기준.md 의 "기준N" 줄에서 읽어 옵니다.
       완료기준.md 에 적혀 있는데 이 스크립트가 검사하지 않는 기준이 있으면
       그것 자체를 실패로 처리합니다. 기준과 검사기가 따로 노는 것을 막기 위해서입니다.
       (완료기준.md 가 없으면 위 네 가지를 기본값으로 씁니다.)
     - 허용되는 색과 글자 크기는 디자인.md 의 1번·2번 표에서 읽어 옵니다.
       디자인.md 를 고치면 검사 기준도 같이 바뀝니다.

   기계가 셀 수 없는 것은 검사하지 않습니다.
   예: 해설 내용이 자료와 실제로 맞는지, 문제가 어려운지, 색이 예뻐 보이는지.
   ============================================================ */

import { readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { runInNewContext } from "node:vm";

const HERE = dirname(fileURLToPath(import.meta.url));

const 대상    = join(HERE, "시험대비.html");
const 디자인  = join(HERE, "디자인.md");
const 완료기준 = join(HERE, "완료기준.md");

const 최소_문제수 = 10;

/* ---------- 결과를 모으는 곳 ---------- */

const 결과 = [];   /* { 기준, 이름, 통과, 자세히 } */

function 기록(기준, 이름, 통과, 자세히 = "") {
  결과.push({ 기준, 이름, 통과, 자세히 });
}

function 읽기(경로, 무엇) {
  if (!existsSync(경로)) {
    console.error(`검사를 할 수 없습니다: ${무엇} 파일이 없습니다 — ${경로}`);
    process.exit(2);
  }
  return readFileSync(경로, "utf8");
}

/* ---------- 파일 읽기 ---------- */

const html     = 읽기(대상, "검사 대상");
const designMd = 읽기(디자인, "디자인 기준");

/* ---------- 완료기준.md 에서 기준 목록 읽기 ---------- */

const 기본기준 = new Map([
  [1, "문제가 10개 이상이다"],
  [2, "모든 문제에 정답과 해설이 있다"],
  [3, "모든 해설에 출처 파일명(.md)이 적혀 있다"],
  [4, "디자인.md 표에 있는 글자 크기와 색만 쓴다"],
]);

/** "- [x] 기준1 · 문제가 10개 이상이다" 같은 줄에서 번호와 문장을 뽑는다 */
function 기준목록읽기(본문) {
  const 목록 = new Map();
  const re = /^\s*-\s*\[[ xX]\]\s*기준\s*(\d+)\s*[·:.\-]?\s*(.+?)\s*$/gm;
  let m;
  while ((m = re.exec(본문)) !== null) {
    목록.set(Number(m[1]), m[2]);
  }
  return 목록;
}

let 기준 = 기본기준;
let 기준출처 = "완료기준.md 가 없어 기본값 사용";

if (existsSync(완료기준)) {
  const 읽은기준 = 기준목록읽기(readFileSync(완료기준, "utf8"));
  if (읽은기준.size > 0) {
    기준 = 읽은기준;
    기준출처 = "완료기준.md";
  } else {
    console.log("알림: 완료기준.md 는 있는데 '기준N' 줄을 찾지 못했습니다. 기본값으로 검사합니다.\n");
  }
} else {
  console.log("알림: 완료기준.md 가 이 폴더에 없습니다. 기본 네 가지 기준으로 검사합니다.\n");
}

/* ============================================================
   기준 뽑아내기 — 디자인.md 의 표에서 읽는다
   ============================================================ */

/** 디자인.md 에서 "## N." 로 시작하는 장 하나를 통째로 잘라낸다.
    마지막 장도 빠짐없이 잡히도록 "## " 기준으로 나눠서 고른다. */
function 장(번호) {
  const 조각 = designMd.split(/^## /m);
  const 찾음 = 조각.find((덩어리) => 덩어리.startsWith(`${번호}.`));
  return 찾음 ?? "";
}

/** 그 장의 표(| 로 시작하는 줄)에서만 값을 뽑는다 */
function 표의줄(본문) {
  return 본문.split("\n").filter((줄) => 줄.trim().startsWith("|"));
}

/** #abc 를 #aabbcc 로 펴서 비교할 수 있게 만든다 */
function 색정규화(hex) {
  const h = hex.toLowerCase();
  if (h.length === 4) {
    return "#" + h[1] + h[1] + h[2] + h[2] + h[3] + h[3];
  }
  return h;
}

const 허용색 = new Set(
  표의줄(장(1))
    .join("\n")
    .match(/#[0-9a-fA-F]{3,6}\b/g)
    ?.map(색정규화) ?? []
);

const 허용크기 = new Set(
  표의줄(장(2))
    .join("\n")
    .match(/[0-9.]+px/g)
    ?.map((s) => s.toLowerCase()) ?? []
);

if (허용색.size === 0 || 허용크기.size === 0) {
  console.error("디자인.md 의 1번 표(색) 또는 2번 표(글자 크기)를 읽지 못했습니다.");
  process.exit(2);
}

/* ============================================================
   시험대비.html 에서 문제 목록 꺼내기
   ============================================================ */

function 문제목록읽기(원문) {
  const 시작 = 원문.indexOf("var QUESTIONS = [");
  if (시작 === -1) return null;

  const 끝 = 원문.indexOf("\n];", 시작);
  if (끝 === -1) return null;

  const 배열 = 원문.slice(원문.indexOf("[", 시작), 끝 + 2);

  try {
    /* 이 파일 안의 배열 리터럴만 값으로 바꿔 읽는다.
       바깥 것은 아무것도 넘겨주지 않는다. */
    return runInNewContext(`(${배열})`, Object.create(null), { timeout: 1000 });
  } catch {
    return null;
  }
}

const 문제 = 문제목록읽기(html);

if (문제 === null || !Array.isArray(문제)) {
  console.error("시험대비.html 에서 문제 목록(QUESTIONS)을 찾지 못했습니다.");
  process.exit(2);
}

/* ============================================================
   검사 1 — 문제가 10개 이상인가
   ============================================================ */

기록(
  1, `문제 개수가 ${최소_문제수}개 이상`,
  문제.length >= 최소_문제수,
  `${문제.length}개`
);

/* ============================================================
   검사 2 — 모든 문제에 정답과 해설이 있는가
   ============================================================ */

const 정답없음 = [];
const 해설없음 = [];

문제.forEach((q, i) => {
  const 번호 = i + 1;

  const 보기수 = Array.isArray(q.choices) ? q.choices.length : 0;
  const 정답있음 =
    Number.isInteger(q.answer) && q.answer >= 0 && q.answer < 보기수;
  if (!정답있음) 정답없음.push(번호);

  const 해설있음 = typeof q.explain === "string" && q.explain.trim().length > 0;
  if (!해설있음) 해설없음.push(번호);
});

기록(
  2, "모든 문제에 정답이 있음",
  정답없음.length === 0,
  정답없음.length === 0
    ? `${문제.length}문제 전부`
    : `정답이 없거나 보기 범위를 벗어난 문제: ${정답없음.join(", ")}번`
);

기록(
  2, "모든 문제에 해설이 있음",
  해설없음.length === 0,
  해설없음.length === 0
    ? `${문제.length}문제 전부`
    : `해설이 빠진 문제: ${해설없음.join(", ")}번`
);

/* ============================================================
   검사 3 — 모든 해설에 출처 파일명(.md)이 적혀 있는가
   ============================================================ */

const 파일명패턴 = /[0-9A-Za-z가-힣_\-]+\.md/;
const 출처없음 = [];

문제.forEach((q, i) => {
  const 출처 = typeof q.src === "string" ? q.src : "";
  if (!파일명패턴.test(출처)) 출처없음.push(i + 1);
});

기록(
  3, "모든 해설에 출처 파일명(.md)이 적힘",
  출처없음.length === 0,
  출처없음.length === 0
    ? `${문제.length}문제 전부`
    : `출처 파일명이 없는 문제: ${출처없음.join(", ")}번`
);

/* ============================================================
   검사 4 — 디자인.md 1번 표의 색만 썼는가
   ============================================================ */

const 쓴색 = [...new Set((html.match(/#[0-9a-fA-F]{3,6}\b/g) ?? []).map(색정규화))];
const 규칙밖색 = 쓴색.filter((c) => !허용색.has(c)).sort();

기록(
  4, "디자인.md 1번 표에 있는 색만 사용",
  규칙밖색.length === 0,
  규칙밖색.length === 0
    ? `색 ${쓴색.length}종, 전부 표 안의 값`
    : `표에 없는 색: ${규칙밖색.join(", ")}`
);

/* ============================================================
   검사 5 — 디자인.md 2번 표의 글자 크기만 썼는가
   ============================================================ */

const 쓴크기 = [
  ...new Set(
    (html.match(/font-size:\s*[0-9.]+px/g) ?? []).map((s) =>
      s.replace(/font-size:\s*/, "").toLowerCase()
    )
  ),
];
const 규칙밖크기 = 쓴크기
  .filter((s) => !허용크기.has(s))
  .sort((a, b) => parseFloat(a) - parseFloat(b));

기록(
  4, "디자인.md 2번 표에 있는 글자 크기만 사용",
  규칙밖크기.length === 0,
  규칙밖크기.length === 0
    ? `크기 ${쓴크기.length}종, 전부 표 안의 값`
    : `표에 없는 크기: ${규칙밖크기.join(", ")}`
);

/* ============================================================
   출력
   ============================================================ */

/* 완료기준.md 에 적혀 있는데 이 스크립트가 검사하지 않는 기준이 있으면
   그것도 실패로 남긴다. 기준만 늘고 검사기가 따라가지 못하는 상태를 막는다. */
const 검사한기준 = new Set(결과.map((r) => r.기준));

for (const [번호, 문장] of [...기준.entries()].sort((a, b) => a[0] - b[0])) {
  if (!검사한기준.has(번호)) {
    기록(번호, `${문장}`, false, "이 기준을 검사하는 코드가 검사.mjs 에 없습니다");
  }
}

결과.sort((a, b) => a.기준 - b.기준);

console.log(`검사 대상 : 시험대비.html (문제 ${문제.length}개)`);
console.log(`완료 기준 : ${기준출처} — 기준 ${기준.size}개`);
console.log(`모양 기준 : 디자인.md — 색 ${허용색.size}종, 글자 크기 ${허용크기.size}종`);
console.log("-".repeat(68));

for (const r of 결과) {
  const 표시 = r.통과 ? "통과" : "실패";
  const 이름 = `기준${r.기준} · ${r.이름}`;
  console.log(`[${표시}] ${이름}${r.자세히 ? " — " + r.자세히 : ""}`);
}

const 실패수 = 결과.filter((r) => !r.통과).length;

console.log("-".repeat(68));
console.log(`실패 ${실패수}건 / 전체 ${결과.length}항목`);

if (실패수 > 0) {
  console.log("실패가 있으므로 종료합니다.");
  process.exit(1);
}

console.log("모두 통과했습니다.");
process.exit(0);
